type LocaleContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string, values?: Record<string, string>) => string
}

function resolveMessage(locale: Locale, key: string, values?: Record<string, string>) {
  let message = messages[locale][key] ?? messages.es[key] ?? key
  for (const [name, value] of Object.entries(values ?? {})) {
    message = message.replaceAll(`{${name}}`, value)
  }
  return message
}

const defaultLocaleContext: LocaleContextValue = {
  locale: 'es',
  setLocale: () => undefined,
  t: (key, values) => resolveMessage('es', key, values),
}

const LocaleContext = createContext<LocaleContextValue>(defaultLocaleContext)

function getSavedLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(localeStorageKey)
    const savedLocale = stored ?? undefined
    return isLocale(savedLocale) ? savedLocale : 'es'
  } catch {
    return 'es'
  }
}

function saveLocale(locale: Locale) {
  try {
    window.localStorage.setItem(localeStorageKey, locale)
  } catch {
    // The URL remains the source of truth if storage is unavailable.
  }
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const location = useLocation()
  const navigate = useNavigate()
  const pathLocale = getLocaleFromPath(location.pathname)
  const [locale, setLocaleState] = useState<Locale>(() => pathLocale ?? getSavedLocale())
  const pendingLocaleRef = useRef<Locale | null>(null)

  useEffect(() => {
    document.documentElement.lang = localeTags[locale]
  }, [locale])

  useEffect(() => {
    const pendingLocale = pendingLocaleRef.current
    const reachedPendingLocale = pendingLocale && (pathLocale === pendingLocale || (!pathLocale && pendingLocale === 'es'))
    if (pendingLocale && !reachedPendingLocale) return
    if (reachedPendingLocale) pendingLocaleRef.current = null

    if (pathLocale) {
      if (pathLocale !== locale) setLocaleState(pathLocale)
      saveLocale(pathLocale)

      if (pathLocale === 'es') {
        const canonicalPath = withLocale(location.pathname, 'es')
        if (canonicalPath !== location.pathname) {
          void navigate(`${canonicalPath}${location.search}${location.hash}`, { replace: true })
        }
      }
      return
    }

    const savedLocale = getSavedLocale()
    if (savedLocale !== locale) setLocaleState(savedLocale)
    if (savedLocale !== 'es') {
      const localizedPath = withLocale(location.pathname, savedLocale)
      void navigate(`${localizedPath}${location.search}${location.hash}`, { replace: true })
    }
  }, [location.hash, location.pathname, location.search, locale, navigate, pathLocale])

  const setLocale = useCallback((nextLocale: Locale) => {
    pendingLocaleRef.current = nextLocale
    saveLocale(nextLocale)
    setLocaleState(nextLocale)
    const pathname = withLocale(location.pathname, nextLocale)
    void navigate(`${pathname}${location.search}${location.hash}`)
  }, [location.hash, location.pathname, location.search, navigate])

  const t = useCallback((key: string, values?: Record<string, string>) => {
    return resolveMessage(locale, key, values)
  }, [locale])

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t])
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  return useContext(LocaleContext)
}
